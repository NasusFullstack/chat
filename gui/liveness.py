"""연결이 아직 살아 있는지 판단하는 정책(소켓도 위젯도 모르는 순수 계산).

왜 필요한가: TCP는 한쪽이 조용히 사라져도 남은 쪽이 한참 모른다. 노트북이 잠들거나
공유기/와이파이가 연결을 버리면, 우리 화면에는 멀쩡히 접속된 것처럼 보이는데 실제로는
아무 것도 오가지 않는다. 그동안 보낸 메시지는 그냥 사라진다.

IRC 서버는 이 상황을 자기 나름으로 판단해서 끊는다 - home.pdlab.kr(UnrealIRCd)은
**180초 동안 우리 응답이 없으면** 끊고 "Ping timeout: 180 seconds"를 남긴다. 그러면
우리는 "왜 팅겼는지" 모른 채 튕겨 나간 것처럼 보인다.

그래서 서버가 물어보기를 기다리지 말고 **우리가 먼저 확인한다.**
- 얼마간 아무 것도 안 오면: 우리가 핑을 보내본다(살아 있으면 바로 답이 온다)
- 그러고도 계속 조용하면: 죽은 연결로 보고 다시 붙는다(서버가 끊기 전에 우리가 먼저)

핑은 한 줄짜리라 서버에 부담이 없다. 사람이 대화 중이면 오가는 게 있으므로 아예 안 보낸다.
"""

# 실측(2026-08-13, home.pdlab.kr에 붙어 7분간 가만히 있어봄):
#   서버가 **90초마다** PING을 보내고, 우리가 답하면 그걸로 연결이 유지된다.
#   180초(핑 두 번) 동안 답이 없으면 "Ping timeout: 180 seconds"로 끊는다.
#
# 그래서 기준을 이렇게 잡는다.
# - 정상이라면 90초마다 뭔가 오므로, 120초까지 조용한 것은 이미 비정상이다.
#   이때 우리가 핑을 보내본다(정상일 때는 이 줄이 아예 안 나간다 = 서버에 부담 0)
# - 170초까지 조용하면 죽은 연결이다. 서버가 끊는 180초보다 **먼저** 우리가 다시 붙는다
#   (서버가 먼저 끊으면 사용자는 "그냥 팅겼다"고만 느끼고 복구도 늦다)
PING_AFTER_SEC = 120
DEAD_AFTER_SEC = 170
# 서버가 핑을 보내는 주기(위 기준을 정한 근거 - 서버 설정이 바뀌면 같이 재봐야 한다)
SERVER_PING_INTERVAL_SEC = 90
SERVER_TIMEOUT_SEC = 180

OK = "ok"
PING = "ping"
DEAD = "dead"


def action_for(silence_sec: float) -> str:
    """마지막으로 뭔가 받은 지 이만큼 지났을 때 무엇을 할지."""
    if silence_sec >= DEAD_AFTER_SEC:
        return DEAD
    if silence_sec >= PING_AFTER_SEC:
        return PING
    return OK
