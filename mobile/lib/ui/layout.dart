/// 화면이 넓은가 좁은가 - 레이아웃을 가르는 **단 하나의 규칙**.
///
/// 기기 수만큼 화면을 만들지 않는다. 실제로 재보면 바 형태 폰은 전부 비슷하다:
///
/// | 기기 | 가로(dp) |
/// |---|---|
/// | 갤S23+ | ~393 |
/// | 갤S25+ / S25 Ultra | ~411 |
/// | 폴드 접은 바깥 화면 | ~369 |
/// | **폴드 편 안쪽 화면** | **~832** |
///
/// 차이가 40dp 남짓(글자 한두 개 폭)이라 같은 레이아웃으로 덮인다. 진짜 다른 건
/// 폴드를 폈을 때뿐이다.
///
/// ## 폴드는 **돌아가는 중에** 바뀐다
/// 접었다 펴면 레이아웃이 그 자리에서 다시 잡힌다. 그때 스크롤 위치나 쓰던 글이 날아가면
/// 안 된다 - PC 앱에서 "창 가로를 줄이면 프로그램이 터진다"가 났던 것과 같은 종류의
/// 위험이다(배치가 바뀌는 순간이 위험하다). 그래서 넓고 좁은 화면이 **같은 상태를**
/// 보게 만들고, 레이아웃만 갈아끼운다.
library;

import 'package:flutter/widgets.dart';

/// 이 폭부터는 두 칸으로 나눠도 답답하지 않다.
///
/// 폴드를 편 화면은 832×750으로 **거의 정사각형**이다. 세 칸으로 쪼개면 한 칸이
/// 270dp밖에 안 돼서 오히려 좁아진다 - 그래서 넓어도 두 칸까지만 간다.
const double wideBreakpoint = 600;

bool isWide(BuildContext context) =>
    MediaQuery.sizeOf(context).width >= wideBreakpoint;

/// 넓은 화면에서 왼쪽(채널 목록)이 차지할 폭.
const double sidePaneWidth = 240;
